CREATE INDEX "IDX_ZJFK_LLM_RULE_TASK_CANDIDATE" ON "ZJFK_LLM_RULE_TASK"("CANDIDATE_ID", "CANDIDATE_VERSION");

CREATE TABLE "ZJFK_LLM_RULE_ARTIFACT" (
