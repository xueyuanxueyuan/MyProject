    CONSTRAINT "CK_ZJFK_LLM_RULE_STATUS" CHECK ("TASK_STATUS" IN ('DRAFT','WAITING_NETWORK','RUNNING','UNKNOWN','FAILED','SUCCEEDED','CANCELLED'))
