SELECT CAST(CAST(SUBSTR(TRIM(TJZQ), 5, 2) AS INTEGER) AS VARCHAR(2)) || '月' AS month,
       CAST(SUBSTR(TRIM(TJZQ), 5, 2) AS INTEGER) AS month_num,
       ROUND(SUM(CASE WHEN HKYWLX IN ('03', '04') THEN DYHSBJ ELSE 0 END) / 10000, 2) AS tqhk,
       ROUND(SUM(CASE WHEN HKYWLX NOT IN ('03', '04') THEN DYHSBJ ELSE 0 END) / 10000, 2) AS zchk
FROM CAP_GJJ_ETL.DWS_BUS_LN_REC_MFM
WHERE SUBSTR(TRIM(TJZQ), 1, 4) = CAST(#{ssnd} AS VARCHAR(4))
GROUP BY CAST(SUBSTR(TRIM(TJZQ), 5, 2) AS INTEGER)
ORDER BY month_num
